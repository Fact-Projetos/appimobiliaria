-- Módulo Financeiro: lançamentos de receitas (Airbnb e "Por fora")
-- Execute no Supabase: SQL Editor > New query > colar e rodar.

create table if not exists public.financial_entries (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  origin         text not null check (origin in ('Airbnb', 'Por fora')),
  entry_date     date not null,
  property_title text not null,
  days           integer not null default 0,
  gross_value    numeric(12,2) not null default 0,
  cleaning       numeric(12,2) not null default 0,
  maintenance    numeric(12,2) not null default 0,
  platform_fees  numeric(12,2) not null default 0,
  net_value      numeric(12,2) not null default 0,
  period_start   date,
  period_end     date,
  notes          text
);

create index if not exists financial_entries_entry_date_idx on public.financial_entries (entry_date);

alter table public.financial_entries enable row level security;

-- Somente usuários logados (administradores) podem ler e alterar.
drop policy if exists "financial_entries_admin_all" on public.financial_entries;
create policy "financial_entries_admin_all"
  on public.financial_entries
  for all
  to authenticated
  using (true)
  with check (true);
